"""Build the reviewer notebooks in notebooks/ from the scripts, which stay the single source of truth.

Each "# ----..." section marker of a script becomes a notebook cell, the module docstring becomes the opening
markdown cell, and Kaggle placeholders get runnable defaults. Rerun after editing a script:
    python3 tools/make_notebooks.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NB = ROOT / "notebooks"
NB.mkdir(exist_ok=True)


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n").splitlines(keepends=True)}


def code(text):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
            "source": text.strip("\n").splitlines(keepends=True)}


def script_cells(path, replace=()):
    src = path.read_text()
    for old, new in replace:
        assert old in src, f"{path.name}: {old!r} not found"
        src = src.replace(old, new)
    doc = re.match(r'\s*"""(.*?)"""\n', src, re.S)
    body = src[doc.end():] if doc else src
    body = re.sub(r'\nif __name__ == "__main__":\n((?:    .*\n?)+)', lambda m: "\n# ---------------------------------------------------------------- run\n"
                  + re.sub(r"^    ", "", m.group(1), flags=re.M), body)
    cells = []
    for chunk in re.split(r"\n(?=# -{8,})", body):
        title = re.match(r"# -{8,}\s*(.*)\n", chunk)
        if title and title.group(1):
            cells.append(md(f"### {title.group(1)[0].upper()}{title.group(1)[1:]}"))
        if chunk.strip():
            cells.append(code(chunk))
    return (doc.group(1).strip() if doc else ""), cells


def write(name, cells):
    nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 5}
    (NB / name).write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote notebooks/{name} ({len(cells)} cells)")


